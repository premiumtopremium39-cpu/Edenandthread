-- 4.2 Auto create profile when a user signs up via Supabase Auth
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
DECLARE
    user_role TEXT := 'customer';
BEGIN
    -- If user email is admin, assign admin role automatically
    IF NEW.email = 'edenandthreadlogin@gmail.com' OR NEW.email = 'admin@mail.com' OR NEW.email = 'admin@edenthreads.luxury' THEN
        user_role := 'admin';
    END IF;

    INSERT INTO public.profiles (id, email, full_name, role, avatar_url)
    VALUES (
        NEW.id,
        NEW.email,
        COALESCE(NEW.raw_user_meta_data->>'full_name', NEW.raw_user_meta_data->>'name', split_part(NEW.email, '@', 1)),
        user_role,
        NEW.raw_user_meta_data->>'avatar_url'
    )
    ON CONFLICT (id) DO UPDATE
    SET 
        email = EXCLUDED.email,
        full_name = COALESCE(EXCLUDED.full_name, profiles.full_name),
        avatar_url = COALESCE(EXCLUDED.avatar_url, profiles.avatar_url),
        updated_at = TIMEZONE('utc'::text, NOW());

    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT OR UPDATE ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- 4.3 Check if current authenticated user is an administrator
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN AS $$
BEGIN
    RETURN EXISTS (
        SELECT 1 FROM public.profiles
        WHERE id = auth.uid() AND role = 'admin'
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 4.4 Secure order tracking function (Allows lookup without exposing private database table to scraping)
CREATE OR REPLACE FUNCTION public.track_order(p_order_id TEXT, p_email TEXT DEFAULT NULL)
RETURNS TABLE (
    order_id TEXT,
    customer_name TEXT,
    order_status TEXT,
    carrier TEXT,
    tracking_number TEXT,
    items JSONB,
    total_amount NUMERIC,
    created_at TIMESTAMPTZ
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        o.order_id,
        o.customer_name,
        o.order_status,
        o.carrier,
        o.tracking_number,
        o.items,
        o.total_amount,
        o.created_at
    FROM public.orders o
    WHERE LOWER(o.order_id) = LOWER(TRIM(p_order_id))
       OR (p_email IS NOT NULL AND LOWER(o.customer_email) = LOWER(TRIM(p_email)) AND LOWER(o.order_id) = LOWER(TRIM(p_order_id)))
    LIMIT 1;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

